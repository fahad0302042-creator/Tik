#!/usr/bin/env python3
"""Static checks that keep the Tik TV fork separated from upstream Cloudstream.

Run with:  python3 scripts/validate_fork.py
Exits non-zero when a fork invariant is broken, so it can run in CI before the build.
"""

from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OFFICIAL_APPLICATION_ID = "com.lagradost.cloudstream3"
OFFICIAL_UPDATE_SLUG = "recloudstream/cloudstream"

failures: list[str] = []
checks = 0


def check(condition: bool, message: str) -> bool:
    global checks
    checks += 1
    if not condition:
        failures.append(message)
    return condition


def read(path: str) -> str:
    return (ROOT / path).read_text(encoding="utf-8", errors="replace")


def props(path: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for line in (ROOT / path).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


# --------------------------------------------------------------------------- identity
grad = props("gradle.properties")
application_id = grad.get("tiktv.applicationId", "")
check(bool(application_id), "gradle.properties is missing tiktv.applicationId")
check(
    application_id != OFFICIAL_APPLICATION_ID,
    "tiktv.applicationId must differ from the official Cloudstream id so both apps can coexist",
)
check(
    bool(re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z][A-Za-z0-9_]*)+", application_id or "#")),
    f"tiktv.applicationId '{application_id}' is not a valid Android application id",
)
check(bool(grad.get("tiktv.appName")), "gradle.properties is missing tiktv.appName")
check(
    (grad.get("tiktv.sourceUrl") or "").startswith("https://github.com/"),
    "tiktv.sourceUrl must be an https GitHub URL",
)
check(
    bool(re.fullmatch(r"[0-9a-f]{40}", grad.get("tiktv.upstreamCommit", ""))),
    "tiktv.upstreamCommit must be the full 40 character upstream commit sha",
)
check(
    (grad.get("tiktv.versionCode") or "").isdigit() and int(grad.get("tiktv.versionCode") or "0") > 0,
    "tiktv.versionCode must be a positive integer",
)

build = read("app/build.gradle.kts")
check(
    'namespace = "com.lagradost.cloudstream3"' in build,
    "The Android namespace must stay com.lagradost.cloudstream3 or extensions stop loading",
)
for field in (
    "FORK_NAME",
    "FORK_SOURCE_URL",
    "FORK_UPSTREAM_COMMIT",
    "FORK_APP_UPDATES_ENABLED",
    "FORK_UPDATE_OWNER",
    "FORK_UPDATE_REPOSITORY",
):
    check(f'"{field}"' in build, f"app/build.gradle.kts is missing the BuildConfig field {field}")

# --------------------------------------------------------------------------- branding
branding_conflicts: list[str] = []
for strings in ROOT.glob("app/src/main/res/values*/strings.xml"):
    text = strings.read_text(encoding="utf-8", errors="replace")
    for name in ("app_name", "play_with_app_name"):
        if re.search(rf'<string name="{name}"', text):
            branding_conflicts.append(f"{strings.relative_to(ROOT)}:{name}")
check(
    not branding_conflicts,
    "app_name/play_with_app_name are generated by Gradle; remove these hardcoded copies: "
    + ", ".join(branding_conflicts),
)

for drawable in ("fork_icon.xml", "fork_banner.xml"):
    check(
        (ROOT / "app/src/main/res/drawable" / drawable).is_file(),
        f"app/src/main/res/drawable/{drawable} is missing",
    )

manifest = read("app/src/main/AndroidManifest.xml")
check("@drawable/fork_banner" in manifest, "The manifest banner must use @drawable/fork_banner")
check("@drawable/fork_icon" in manifest, "The manifest icon must use @drawable/fork_icon")
check(
    "${applicationId}.downloadedplayer" in manifest,
    "The downloaded player task affinity must stay scoped to this application id",
)
check(
    "android.intent.category.LEANBACK_LAUNCHER" in manifest,
    "The manifest needs a LEANBACK_LAUNCHER category to appear on Android TV",
)

# --------------------------------------------------------------------------- update isolation
for path in (
    "app/src/main/java/com/lagradost/cloudstream3/utils/InAppUpdater.kt",
    "app/src/main/java/com/lagradost/cloudstream3/ui/settings/GithubReleases.kt",
):
    text = read(path)
    check("FORK_APP_UPDATES_ENABLED" in text or "FORK_UPDATE_OWNER" in text,
          f"{path} must respect the fork update switch so official APKs are never offered")

check(
    "BuildConfig.FORK_NAME" in read("app/src/main/java/com/lagradost/cloudstream3/ui/settings/ApkUpdater.kt"),
    "ApkUpdater.kt must name downloaded files with BuildConfig.FORK_NAME",
)

for path in (
    "app/src/main/java/com/lagradost/cloudstream3/utils/InAppUpdater.kt",
    "app/src/main/java/com/lagradost/cloudstream3/ui/settings/GithubReleases.kt",
    "app/src/main/java/com/lagradost/cloudstream3/ui/settings/ApkUpdater.kt",
    "app/src/main/java/com/lagradost/cloudstream3/MainActivityScreen.kt",
):
    text = read(path)
    check(
        OFFICIAL_UPDATE_SLUG not in text,
        f"{path} still points at the official update repository ({OFFICIAL_UPDATE_SLUG})",
    )

check(
    grad.get("tiktv.updateRepository") != "cloudstream",
    "tiktv.updateRepository must not be the upstream cloudstream repository",
)

# --------------------------------------------------------------------------- tv behavior
check(
    (ROOT / "app/src/main/java/com/lagradost/cloudstream3/utils/ForkTvHelper.kt").is_file(),
    "ForkTvHelper.kt is missing",
)
fork_config = ROOT / "app/src/main/res/values/fork_config.xml"
check(fork_config.is_file(), "res/values/fork_config.xml is missing")
if fork_config.is_file():
    value = re.search(r'name="fork_default_tv_overscan_dp">(\d+)<', fork_config.read_text())
    check(bool(value), "fork_default_tv_overscan_dp is missing")
    if value:
        check(
            0 <= int(value.group(1)) <= 100,
            "fork_default_tv_overscan_dp must stay between 0 and 100 dp",
        )

# --------------------------------------------------------------------------- docs & license
check((ROOT / "LICENSE").is_file(), "The GPL-3.0 LICENSE must stay in the fork")
check(
    (ROOT / "docs" / "FORK_NOTICES.md").is_file(),
    "docs/FORK_NOTICES.md must document the upstream source and modifications",
)
readme = read("README.md") if (ROOT / "README.md").is_file() else ""
check(
    "Cloudstream" in readme and grad.get("tiktv.upstreamCommit", "") in readme,
    "README.md must credit upstream Cloudstream and pin the imported commit",
)

# --------------------------------------------------------------------------- xml sanity
bad_xml: list[str] = []
for xml in ROOT.glob("app/src/main/res/**/*.xml"):
    try:
        ET.parse(xml)
    except ET.ParseError as error:
        bad_xml.append(f"{xml.relative_to(ROOT)}: {error}")
check(not bad_xml, "Malformed XML resources: " + "; ".join(bad_xml))

# --------------------------------------------------------------------------- report
print(f"Ran {checks} fork checks")
if failures:
    for failure in failures:
        print(f"  FAIL  {failure}")
    print(f"{len(failures)} check(s) failed")
    sys.exit(1)
print("All fork checks passed")
